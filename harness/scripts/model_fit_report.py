"""Generate `harness/docs/MODEL-FIT.md` from the inventory and the fit probe - no number typed by hand.

Two inputs, because the question has two halves: `model_inventory.py` says what each file IS (arch, channels,
which opt-ins its structure allows) and `model_fit_probe.py` says what happened when the body was actually
built on it (gross-error share on three held-out frames, body time against the model's own fp16 forward).

Usage: python harness/scripts/model_fit_report.py [--inventory ...] [--fit ...] [--out harness/docs/MODEL-FIT.md]
"""
from __future__ import annotations

import argparse
import json
import os
import statistics
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--inventory", default="harness/docs/wsp/verified/logs/model-fit/inventory.json")
    ap.add_argument("--fit", default="harness/docs/wsp/verified/logs/model-fit/all.json")
    ap.add_argument("--fit-pc", default="harness/docs/wsp/verified/logs/model-fit/all-perchannel.json",
                    help="the same sweep with RVE_INT8_PER_CHANNEL=1; the two grids are compared per model")
    ap.add_argument("--out", default="harness/docs/MODEL-FIT.md")
    args = ap.parse_args(argv)

    inv = json.load(open(args.inventory))
    fit = json.load(open(args.fit))
    rows_inv = {r["file"]: r for r in inv["rows"]}
    pc = {}
    if args.fit_pc and os.path.exists(args.fit_pc):
        pc = {r["file"]: r for r in json.load(open(args.fit_pc))["rows"] if "share" in r}
    fit_rows = [r for r in fit["rows"] if "share" in r and "error" not in r]
    err_rows = [r for r in fit["rows"] if "error" in r]
    counts = inv["counts"]
    total = len(inv["rows"])

    def cls(r):
        return {"FULL": 0, "BODY+TAIL": 1, "BODY": 2}.get(r["verdict"], 3)

    fit_rows.sort(key=lambda r: (cls(r), r["share"]))
    full = [r for r in fit_rows if r["verdict"] == "FULL"]
    times = [r["int8_ms"] for r in full]
    spread = 100.0 * (max(times) - min(times)) / statistics.median(times)
    over_gate = [r for r in fit_rows if r["share"] > 1.0]
    within = [r for r in fit_rows if r["share"] <= 1.0]
    closest = max(within, key=lambda r: r["share"]) if within else None
    cleanest = [r for r in fit_rows if r["share"] <= 0.0001]

    L = []
    A = L.append
    A("# Which of the collection's models this pipeline can run")
    A("")
    A("Generated by `harness/scripts/model_fit_report.py` from `model_inventory.py` (what each file IS) and")
    A("`model_fit_probe.py` (what happened when the int8 body was built on it). Records:")
    A("`harness/docs/wsp/verified/records/model-fit.jsonl`; raw: `logs/model-fit/all.json`.")
    A("")
    A("## The question, and the boundary that answers most of it")
    A("")
    A("`Int8Body` needs a Compact/SRVGG body: **sixteen 64-channel convolutions** between the head and the tail.")
    A("That is not a preference - the channel count is a `tl.constexpr` in the Triton kernel, so a model of")
    A("another width or another family has nothing for the kernel to replace. Around that core sit four opt-ins")
    A("with their own preconditions (head fused: a plain 3->64 head; tail int8: <=16 output channels; shuffle")
    A("fold: `nn.PixelShuffle` r=2 with 12 tail channels; tail CSC: needs the fold).")
    A("")
    A(f"Of **{total} distinct model files** in the collection:")
    A("")
    A("| verdict | count | meaning |")
    A("|---|---|---|")
    A(f"| **FULL** | {counts['FULL']} | every opt-in applies: int8 hops, int8 tail, shuffle fold, the tail writing "
      f"the pipe payload |")
    A(f"| BODY+TAIL | {counts['BODY+TAIL']} | int8 hops and int8 tail; 1x upsamplers, so no shuffle fold and the "
      f"pack converts colour |")
    A(f"| BODY | {counts['BODY']} | int8 hops only - the tail is wider than the kernel's 16-channel pad "
      f"(4x models carry 48) |")
    A(f"| **NO** | {counts['NO']} | RRDBNet / SPAN / OmniSR / RealPLKSR / DAT families, 24-channel compacts, and "
      f"two files that are not models at all |")
    A("")
    A("## Measured, per model")
    A("")
    A("`share` is the int8 body's gross-error gate against its **own** fp16 model: percent of pixels more than")
    A("8 levels off in any channel, worst of three held-out frames. It is the gate the app applies at start-up")
    A("(1%), **not** the acceptance bar (0.1% on a 494-frame pair) - see the caveat below.")
    A("")
    A("| verdict | model | arch | scale | share, per-tensor | share, per-channel | body int8, ms |")
    A("|---|---|---|---|---|---|---|")
    for r in fit_rows:
        i = rows_inv.get(r["file"], {})
        p = pc.get(r["file"])
        pc_cell = f"{p['share']:.4f}%" if p else "-"
        A(f"| {r['verdict']} | `{r['file']}` | {i.get('arch', '?')} | x{r['scale']} | "
          f"{r['share']:.4f}% | {pc_cell} | {r['int8_ms']:.2f} |")
    unmeasured = [f for f, r in rows_inv.items()
                  if r["verdict"] in ("FULL", "BODY+TAIL", "BODY") and f not in fit and f not in pc]
    if unmeasured:
        A("")
        A(f"{len(unmeasured)} models are structurally compatible but are NOT in this sweep - they became reachable")
        A("after it ran, when the hop-count rule and the width padding landed. The 48/32/24-channel families are")
        A("measured separately on `harness/docs/wsp/verified/int8-native-width.txt` (share and body time, with the padding")
        A("cost stated); the rest need their own run. Listed so the table cannot be read as covering them: "
          + ", ".join(f"`{f}`" for f in unmeasured) + ".")
    if err_rows:
        A("")
        A("Refused at probe time (the inventory said they fit, the build or the gate said otherwise):")
        for r in err_rows:
            A(f"- `{r['file']}` - {r['error']}")
    A("")
    A("## What this says")
    A("")
    A(f"**Model choice does not buy speed.** The {len(full)} FULL models land at "
      f"{min(times):.2f}-{max(times):.2f} ms for the body - a {spread:.1f}% spread that is drift: they are the")
    A("same shape (16x64 convs, 12-channel tail), and the sweep ran them one process at a time, so a warm clock")
    A("is what separates them. What model choice buys is the picture.")
    A("")
    A(f"**The gate separates them.** {len(over_gate)} of {len(fit_rows)} models read above the app's 1%")
    A("start-up gate, i.e. that body would be refused and the fp16 engine would run instead: "
      + ", ".join(f"`{r['file']}` at {r['share']:.4f}%" for r in over_gate) + ".")
    if closest is not None:
        A(f"The worst that still passes is `{closest['file']}` at {closest['share']:.4f}% - inside the 1% gate, but")
        A(f"{closest['share'] / 0.1:.0f} times the 0.1% bar that actually decides a picture, so it would need a")
        A("render pair before anyone trusted it.")
    A("")
    A("**The cleanest quantisers are not the model in production.** "
      + ", ".join(f"`{r['file']}`" for r in cleanest)
      + f" read at or below 0.0001% on all three frames, against "
      f"{next(r['share'] for r in fit_rows if r['file'].endswith('Futsuu-Anime(1).pth')):.4f}% for Futsuu. That is")
    A("a statement about how well each model's activations fit a per-tensor int8 grid, not about which model")
    A("upscales better - the fp16 picture is the model, and int8 only decides how much of it survives.")
    A("")
    A(f"**1x models work but lose the two colour opt-ins.** {counts['BODY+TAIL']} denoise/restore models run")
    A("int8 hops and the int8 tail; their upsampler is not a 2x `PixelShuffle`, so the shuffle fold and the")
    A("payload path do not apply and the pack keeps converting colour. The mechanism would generalise (the fold")
    A("is exact for any r), but the kernel's `scale == 2` condition is what the shipped code checks - a")
    A("deliberate scope line, and the reason a 1x model is not a FULL verdict here.")
    A("")
    A(f"**4x pays twice.** `realesr-animevideov3` (r=4, 48 tail channels) gets hops only and its body reads")
    A(f"{next(r['int8_ms'] for r in fit_rows if r['verdict'] == 'BODY'):.2f} ms - about a third more than the 2x")
    A("models, because the tail stays fp16 and produces 16.6 Mpx instead of 4.1.")
    A("")
    if pc:
        fit_by = {r["file"]: r for r in fit_rows}
        # only models where the grid actually matters: a 2x change of 0.0000% is not a rescue or a damage
        meaningful = {f for f in pc if f in fit_by and max(pc[f]["share"], fit_by[f]["share"]) >= 0.01}
        better = [(f, pc[f]["share"], fit_by[f]["share"]) for f in meaningful
                  if pc[f]["share"] * 3 < fit_by[f]["share"]]
        worse = [(f, pc[f]["share"], fit_by[f]["share"]) for f in meaningful
                 if pc[f]["share"] > fit_by[f]["share"] * 1.5]
        spreads_better = [fit_by[f].get("grid_spread") for f, _a, _b in better]
        spreads_worse = [fit_by[f].get("grid_spread") for f, _a, _b in worse]
        A("## Two grids, and the predictor that failed")
        A("")
        A("`RVE_INT8_PER_CHANNEL=1` makes the int8 grid per channel instead of per tensor. It is not a small")
        A("setting: on the same 21 models it rescues some and damages others.")
        A("")
        A(f"**Rescued** (per-channel at least 3x better): "
          + ", ".join(f"`{f}` {b:.4f}% -> {a:.4f}%" for f, a, b in sorted(better, key=lambda t: -t[2])) + ".")
        A("")
        A(f"**Damaged** (per-channel worse by more than half): "
          + ", ".join(f"`{f}` {b:.4f}% -> {a:.4f}%" for f, a, b in sorted(worse, key=lambda t: t[1])) + ".")
        A("")
        A("The hypothesis this row was filed with was that the calibration grid's dynamic range (`max/median` of")
        A("the per-channel maxima) predicts which models improve. **It does not.** The two groups overlap:")
        A("")
        A(f"- rescued models' spreads: {sorted(round(x, 2) for x in spreads_better if x is not None)}")
        A(f"- damaged models' spreads: {sorted(round(x, 2) for x in spreads_worse if x is not None)}")
        A("")
        A("So the rule is not a threshold on the grid. The implementable version is to **measure both grids and")
        A("keep the better one**, choosing on frames disjoint from the ones the start-up gate certifies on -")
        A("otherwise the gate would pass by construction. That is a small change, and its cost is one extra")
        A("build per render; the alternative (a flag nobody sets) leaves six models looking unquantisable when")
        A("the grid was the problem.")
        A("")
    A("## Not covered")
    A("")
    A("- **The fp16 column in the records is eager PyTorch, not the app's TensorRT engine.** It reads ~204 ms")
    A("  where the engine reads 52.39 ms (`int8-tail-csc.jsonl` JC001), so the ratios in the records compare the")
    A("  BODY ACROSS MODELS. They are not the product's ratio and must not be quoted as one.")
    A("- **n=3 frames of one clip.** The gross gate at 1% is a smoke test; the acceptance statistic needs a")
    A("  494-frame pair per model, and none of these models has one.")
    A("- **No model here was judged on its picture quality.** This page answers \"can the pipeline run it and")
    A("  does the quantiser survive it\", not \"does it upscale well\" - that is a different lane's question and")
    A("  needs the reference frames the model was trained against.")
    A("- **A model swap in the product also rebuilds its TensorRT engine** (one engine file per model). That")
    A("  cost is outside everything measured here.")
    A("")
    A("## Reproduce")
    A("")
    A("```bash")
    A("# what each file IS, from the app's own spandrel loader")
    A("<install-python> harness/scripts/model_inventory.py --json harness/docs/wsp/verified/logs/model-fit/inventory.json")
    A("# what happened when the body was built on it")
    A("flock -n /var/tmp/opencode/gpu.lock <install-python> harness/scripts/model_fit_probe.py \\")
    A("    --out-file harness/docs/wsp/verified/logs/model-fit/all.json")
    A("PYTHONPATH=. python3 harness/scripts/model_fit_records.py")
    A("PYTHONPATH=. python3 harness/scripts/model_fit_report.py")
    A("```")

    open(os.path.join(REPO, args.out), "w").write("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"# -> {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
